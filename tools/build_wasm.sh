#!/bin/sh
# Compile wasm/cnn.c to WebAssembly (with SIMD) and wrap it as a script the
# page and its workers can load: assets/js/cnn-wasm.js.
set -e
cd "$(dirname "$0")/.."
out=$(mktemp -d)
clang --target=wasm32 -O3 -msimd128 -nostdlib -fno-builtin \
  -Wl,--no-entry -Wl,-z,stack-size=65536 -Wl,--initial-memory=1048576 \
  -Wl,--export=prepare -Wl,--export=zero_grads -Wl,--export=export_grads \
  -Wl,--export=train -Wl,--export=predict -Wl,--export=param_count -Wl,--export=max_batch \
  -Wl,--export=params -Wl,--export=grads -Wl,--export=images -Wl,--export=labels -Wl,--export=preds \
  -o "$out/cnn.wasm" wasm/cnn.c
b64=$(base64 -w0 "$out/cnn.wasm")
{
  echo "// Generated by tools/build_wasm.sh from wasm/cnn.c ($(wc -c < "$out/cnn.wasm") bytes). Do not edit."
  echo "(function (root) { (root.BL || (root.BL = {})).cnnWasmBase64 = '$b64'; })(typeof globalThis !== 'undefined' ? globalThis : self);"
} > assets/js/cnn-wasm.js
echo "wrote assets/js/cnn-wasm.js ($(wc -c < "$out/cnn.wasm") bytes of wasm)"
rm -rf "$out"
